#!/usr/bin/env python3
"""Discover clothing from archive contents and prepare independent item assets.

No Blender, rendering, game writes or code from the download. All outputs stay
in CyberMac's working directory. The game supplies the item templates.
"""
import argparse
import copy
import hashlib
import gzip
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import zipfile

# Bundled helpers are signed app resources. Keep Python's import cache out of
# that directory, including when an older app executable invokes this script.
sys.dont_write_bytecode = True

import prepare_lucy_assets as a
from prepare_jinguji_assets import nodes, select_mesh_appearance

VERSION = 1
SLOTS = {
    'player_outer_torso_item': ('Outer torso', 'Items.Vest_08_basic_01'),
    'player_inner_torso_item': ('Inner torso', 'Items.Shirt_01_basic_01'),
    'player_legs_item': ('Legs', 'Items.Pants_09_basic_01'),
    'player_feet_item': ('Feet', 'Items.Boots_01_basic_01'),
    'player_face_item': ('Face', 'Items.Glasses_01_basic_01'),
    'player_head_item': ('Head', 'Items.Cap_01_basic_01'),
}


def atomic_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix('.tmp')
    temporary.write_text(json.dumps(value, indent=2) + '\n')
    temporary.replace(path)


def metadata(path):
    return any(p == '__MACOSX' or p.startswith('._') or p == '.DS_Store' for p in Path(path).parts)


def validate_zip(package):
    infos = package.infolist()
    a.require(len(infos) <= 50_000 and sum(x.file_size for x in infos) <= 1024**3, 'ZIP exceeds clothing limits')
    seen = set()
    for info in infos:
        a.require(info.filename not in seen, 'Duplicate ZIP entry')
        seen.add(info.filename)
        path = Path(info.filename)
        a.require(not path.is_absolute() and '..' not in path.parts and '\\' not in info.filename, 'Unsafe ZIP path')
        a.require((info.external_attr >> 16) & 0o170000 != 0o120000, 'Symbolic links are not supported')
    return [x for x in infos if not x.is_dir() and x.filename.lower().endswith('.archive') and not metadata(x.filename)]


def identity(archive_hash, root, prefix):
    # Colour alternatives that replace the same vanilla mesh must still receive
    # different resource paths, factory keys and item records.
    value = hashlib.sha256((archive_hash + '|' + root + '|' + prefix).encode()).hexdigest()[:20]
    return 'Items.CyberMac_Import_' + value, 'cybermac_import_' + value


def matching_templates(templates, keys):
    matches = [t for t in templates if a.fnv(t['appPath']) in keys or keys.intersection(a.fnv(p) for p in t['meshes'])]
    families = {}
    for template in sorted(matches, key=lambda x: (-len(keys.intersection(a.fnv(p) for p in x['meshes'])), 'basic_01_' not in x['prefix'], x['appPath'], x['prefix'])):
        # Several donor appearances can use one mesh. Show that mesh once per
        # slot, while retaining different garments bundled into one archive.
        replaced = tuple(sorted(keys.intersection(a.fnv(p) for p in template['meshes'])))
        family = (template['root'], replaced or (a.fnv(template['appPath']),))
        families.setdefault(family, template)
    return list(families.values())


def read_json(path):
    with (gzip.open(path, 'rt') if str(path).endswith('.gz') else open(path)) as stream:
        return json.load(stream)


def namespace_paths(value, mapping):
    for node in nodes(value):
        if node.get('$type') == 'ResourcePath' and '$value' in node:
            old = node['$value']
            if node.get('$storage') == 'string' and isinstance(old, str): key = a.fnv(old)
            elif node.get('$storage') == 'uint64' or isinstance(old, int): key = int(str(old), 0) if str(old).startswith('0x') else int(old)
            else: key = None
            if key in mapping:
                node['$storage'] = 'string'
                node['$value'] = mapping[key]


def material_names(mesh):
    return {x.get('Data', x)['name']['$value'] for x in mesh.get('appearances', [])}


def conversion_graph(value):
    """Compare material contents independently of their regenerated byte layout.

    Relocating a material's resource path changes its serialized CR2W length.
    WolvenKit rewrites meshLocalMaterialHeader sizes and following offsets.
    Validate that layout, then compare every decoded material, buffer, reference
    and mesh field; only these derived offset/size numbers are normalized.
    """
    value = copy.deepcopy(value)
    for node in nodes(value):
        if node.get('$type') != 'meshMeshMaterialBuffer': continue
        materials, headers = node.get('materials'), node.get('rawDataHeaders')
        if not isinstance(materials, list) or not isinstance(headers, list): continue
        a.require(len(materials) == len(headers), 'Material header count does not match the decoded materials')
        if not materials: continue
        files = (node.get('rawData') or {}).get('Data', {}).get('Files')
        a.require(isinstance(files, list) and len(files) == len(materials), 'The decoded material buffer is incomplete')
        offset = 0
        for material, file, header in zip(materials, files, headers):
            a.require(a.canonical_graph(material) == a.canonical_graph(file.get('RootChunk')), 'Material buffer contents disagree with its decoded material')
            size = header.get('size')
            a.require(header.get('$type') == 'meshLocalMaterialHeader' and type(header.get('offset')) is int and
                      header['offset'] == offset and type(size) is int and size > 0, 'Invalid local material buffer layout')
            offset += size
            header['offset'] = '<serialized-offset>'
            header['size'] = '<serialized-size>'
    return a.canonical_graph(value)


def compact_templates(cache, templates):
    paths = {t[key] for t in templates for key in ['entityJSON', 'appJSON']}
    for path in paths:
        if path.endswith('.gz'): continue
        source = cache / path
        with source.open('rb') as stream, gzip.open(str(source) + '.gz', 'wb', compresslevel=1) as target:
            shutil.copyfileobj(stream, target)
        for template in templates:
            for key in ['entityJSON', 'appJSON']:
                if template[key] == path: template[key] = path + '.gz'
    for path in (cache / 'decoded').glob('*.json'): path.unlink()


class Converter:
    def __init__(self, request):
        self.request = request
        self.game = Path(request['gameApp']).resolve()
        self.output = Path(request['output']).resolve()
        a.require(self.output != self.game and not self.output.is_relative_to(self.game), 'Clothing output must stay outside the game')
        self.output.mkdir(parents=True, exist_ok=True)
        self.tools = request['tools']
        self.codec = a.Codec(Path(self.tools['kraken']))
        self.env = dict(os.environ, DOTNET_ROLL_FORWARD='Major', DOTNET_PROCESSOR_COUNT='2', OMP_NUM_THREADS='2')
        self.archive_folder = self.game / 'Contents/Data/archive/Mac'
        self.archive_paths = sorted(self.archive_folder.rglob('*.archive'))

    def run(self, command, log, timeout=120):
        result = subprocess.run([str(x) for x in command], env=self.env, capture_output=True, text=True, timeout=timeout)
        (self.output / (log + '.log')).write_text(result.stdout + result.stderr)
        a.require(result.returncode == 0, 'Clothing conversion failed; see ' + log + '.log')
        return result.stdout

    def convert(self, mode, source, destination):
        destination.mkdir(parents=True, exist_ok=True)
        self.run([self.tools['dotnet'], self.tools['wolvenkit'], 'convert', mode, source, '-o', destination], mode + '-' + source.name)

    def extract_official(self, paths, folder):
        pending = {a.fnv(p): p for p in paths}
        found = {}
        folder.mkdir(parents=True, exist_ok=True)
        for archive_path in self.archive_paths:
            bundle = a.Archive(archive_path)
            for key in set(bundle.rows).intersection(pending):
                a.require(key not in found and bundle.rows[key] is not None, 'Ambiguous game resource: ' + pending[key])
                path = pending[key]
                target = folder / (f'{key:016x}' + Path(path.replace('\\', '/')).suffix)
                target.write_bytes(bundle.extract(key, self.codec))
                found[key] = target
        a.require(set(found) == set(pending), 'Missing clothing template resources')
        return {path: found[key] for key, path in pending.items()}

    def templates(self):
        appearance_archive = self.archive_folder / 'content/basegame_4_appearance.archive'
        with appearance_archive.open('rb') as f:
            header = f.read(52)
            f.seek(struct.unpack_from('<Q', header, 8)[0])
            index = f.read(struct.unpack_from('<I', header, 16)[0])
        key = hashlib.sha256(header + index + a.sha(Path(self.tools['wolvenkit'])).encode()).hexdigest()
        cache = Path(self.request['templateCache']) / key
        receipt = cache / 'index.json'
        if receipt.is_file():
            value = json.loads(receipt.read_text())
            if value.get('version') == VERSION and all((cache / x['entityJSON']).is_file() and (cache / x['appJSON']).is_file() for x in value['templates']):
                compact_templates(cache, value['templates'])
                atomic_json(receipt, value)
                return cache, value['templates']
        raw, decoded = cache / 'raw', cache / 'decoded'
        shutil.rmtree(cache, ignore_errors=True)
        cache.mkdir(parents=True)
        listing = self.run([self.tools['dotnet'], self.tools['wolvenkit'], 'archive', appearance_archive,
                            '--list', '--pattern', '*.app'], 'list-clothing-templates')
        apps = sorted({p.strip().replace('/', '\\') for p in listing.splitlines()
                       if p.startswith('base/characters/appearances/player/items/') and p.endswith('.app')})
        a.require(0 < len(apps) <= 256, 'Unexpected clothing template inventory')
        factory_paths = self.extract_official([a.FACTORY], raw)
        self.convert('serialize', raw, decoded)
        factory = json.loads((decoded / (factory_paths[a.FACTORY].name + '.json')).read_text())['Data']['RootChunk']
        roots = {row[0]: row[1] for row in factory['data'] if len(row) >= 2 and row[0] in SLOTS}
        a.require(set(roots) == set(SLOTS), 'Game clothing slots could not be resolved')
        paths = self.extract_official(apps + list(roots.values()), raw)
        self.convert('serialize', raw, decoded)
        app_docs = {p: json.loads((decoded / (paths[p].name + '.json')).read_text()) for p in apps}
        templates = []
        for root, root_path in roots.items():
            root_file = decoded / (paths[root_path].name + '.json')
            entity = json.loads(root_file.read_text())['Data']['RootChunk']
            groups = {}
            for appearance in entity['appearances']:
                name = appearance['name']['$value']
                path = appearance.get('appearanceResource', {}).get('DepotPath', {}).get('$value')
                if '&Female' not in name or path not in app_docs:
                    continue
                prefix = name.split('&', 1)[0]
                groups.setdefault((path, prefix), []).append(appearance['appearanceName']['$value'])
            for (path, prefix), names in groups.items():
                app = app_docs[path]['Data']['RootChunk']
                definitions = [x for x in app.get('appearances', []) if x['Data']['name']['$value'] in names]
                meshes = sorted({p for x in definitions for p in a.depot_paths(x) if p.endswith('.mesh')})
                if not meshes: continue
                templates.append(dict(root=root, source=SLOTS[root][1], slot=SLOTS[root][0], prefix=prefix,
                    entityPath=root_path, appPath=path, meshes=meshes,
                    entityJSON=str(root_file.relative_to(cache)), appJSON=str((decoded / (paths[path].name + '.json')).relative_to(cache))))
        a.require(templates, 'No clothing appearance graphs could be read')
        compact_templates(cache, templates)
        atomic_json(receipt, dict(version=VERSION, templates=templates))
        shutil.rmtree(raw)
        return cache, templates

    def inspect(self):
        package = Path(self.request['package'])
        a.require(a.sha(package) == self.request['packageSHA256'], 'The clothing download changed')
        cache, templates = self.templates()
        items = []
        archives = self.output / 'archives'
        archives.mkdir(exist_ok=True)
        with zipfile.ZipFile(package) as zip_:
            for entry in validate_zip(zip_):
                a.require(entry.file_size <= 80 * 1024**2, 'Garment archive exceeds the 80 MB limit')
                data = zip_.read(entry)
                digest = hashlib.sha256(data).hexdigest()
                archive_path = archives / 'inspecting.archive'
                archive_path.write_bytes(data)
                try:
                    bundle = a.Archive(archive_path)
                    keys = set(bundle.rows)
                    families = matching_templates(templates, keys)
                    for template in families:
                        record, entity = identity(digest, template['root'], template['prefix'])
                        name = Path(entry.filename).stem.replace('_', ' ')
                        items.append(dict(record=record, name=name + (' · ' + template['slot'] if len(families) > 1 else ''), source=template['source'], slot=template['slot'],
                            archivePath=entry.filename, sourceSHA256=digest, entityName=entity,
                            template=template, templateCache=str(cache), problem=None))
                    if not families:
                        items.append(dict(record=None, name=Path(entry.filename).stem.replace('_', ' '), slot='Other',
                            archivePath=entry.filename, sourceSHA256=digest,
                            problem='No matching base-game clothing template. This package may require an add-on definition or a custom body.'))
                except (ValueError, KeyError, struct.error) as error:
                    items.append(dict(record=None, name=Path(entry.filename).stem, slot='Other', archivePath=entry.filename,
                                      sourceSHA256=digest, problem=str(error)))
        result = dict(version=VERSION, packageSHA256=self.request['packageSHA256'], items=items)
        (archives / 'inspecting.archive').unlink(missing_ok=True)
        atomic_json(self.output / 'inspection.json', result)
        return result

    def build(self):
        inspection = self.inspect()
        requested = self.request.get('records', [])
        a.require(requested and len(requested) == len(set(requested)), 'Select clothing to prepare')
        by_id = {x['record']: x for x in inspection['items'] if x.get('record')}
        a.require(set(requested).issubset(by_id), 'Selection does not belong to this ZIP')
        items = [by_id[key] for key in requested]
        work = self.output / ('build-' + hashlib.sha256('|'.join(sorted(requested)).encode()).hexdigest()[:20])
        if work.exists(): shutil.rmtree(work)
        work.mkdir()
        raw, decoded, edits, rebuilt, checked = [work / n for n in ['raw', 'decoded', 'edits', 'rebuilt', 'checked']]
        for folder in [raw, decoded, edits, rebuilt, checked]: folder.mkdir()
        resources, generated, originals = {}, {}, set()
        # Read the current factory so earlier additions remain available.
        factory_archive = Path(self.request.get('baseFactoryArchive') or self.archive_folder / 'content/basegame_4_gamedata.archive')
        factory_bundle = a.Archive(factory_archive)
        (raw / 'factory.csv').write_bytes(factory_bundle.extract(a.fnv(a.FACTORY), self.codec))
        self.convert('serialize', raw, decoded)
        factory = read_json(decoded / 'factory.csv.json')

        def edit(path, doc):
            name = f'{a.fnv(path):016x}' + Path(path.replace('\\', '/')).suffix + '.json'
            a.require(name not in generated, 'Generated clothing identity collision')
            if 'cookingPlatform' in doc['Data']['RootChunk']:
                doc['Data']['RootChunk']['cookingPlatform'] = 'PLATFORM_PC'
            generated[name] = (path, doc)
            (edits / name).write_text(json.dumps(doc))

        with zipfile.ZipFile(self.request['package']) as package:
            for number, item in enumerate(items):
                source = self.output / 'archives' / (item['sourceSHA256'] + '.archive')
                source.write_bytes(package.read(item['archivePath']))
                a.require(a.sha(source) == item['sourceSHA256'], 'A garment archive changed')
                bundle = a.Archive(source)
                template = item['template']
                entity_name = item['entityName']
                namespace = 'cybermac\\imports\\' + entity_name.removeprefix('cybermac_import_') + '\\'
                source_raw, source_json = work / f'source-{number}', work / f'source-json-{number}'
                source_raw.mkdir()
                for key in bundle.rows:
                    data = bundle.extract(key, self.codec)
                    a.require(data.startswith(b'CR2W'), 'This archive includes a non-clothing binary resource')
                    # Serialization reads CR2W's own root type; .mesh is an
                    # accepted input extension even for other resource classes.
                    (source_raw / (f'{key:016x}.mesh')).write_bytes(data)
                self.convert('serialize', source_raw, source_json)
                documents = {key: read_json(source_json / (f'{key:016x}.mesh.json')) for key in bundle.rows}
                entity = copy.deepcopy(documents.get(a.fnv(template['entityPath']))) or read_json(Path(item['templateCache']) / template['entityJSON'])
                app = copy.deepcopy(documents.get(a.fnv(template['appPath']))) or read_json(Path(item['templateCache']) / template['appJSON'])
                entity['Data']['RootChunk']['appearances'] = [x for x in entity['Data']['RootChunk']['appearances']
                    if x['name']['$value'].startswith(template['prefix'] + '&Female')]
                names = {x['appearanceName']['$value'] for x in entity['Data']['RootChunk']['appearances']}
                app['Data']['RootChunk']['appearances'] = [x for x in app['Data']['RootChunk']['appearances'] if x['Data']['name']['$value'] in names]
                a.require(names and names == {x['Data']['name']['$value'] for x in app['Data']['RootChunk']['appearances']}, 'Incomplete clothing appearances')
                paths = {p for p in a.depot_paths(app) if a.fnv(p) in bundle.rows and p.endswith('.mesh')}
                a.require(paths, 'The chosen clothing mesh is missing from the appearance')
                parts = sorted({p for p in a.depot_paths(app) if p.endswith('.ent')})
                part_raw = work / f'parts-{number}'
                part_json = work / f'parts-json-{number}'
                missing_parts = [p for p in parts if a.fnv(p) not in documents]
                extracted_parts = self.extract_official(missing_parts, part_raw) if missing_parts else {}
                if missing_parts: self.convert('serialize', part_raw, part_json)
                extensions = {'CMesh': '.mesh', 'CBitmapTexture': '.xbm', 'CMaterialInstance': '.mi',
                              'MultilayerSetup': '.mlsetup', 'MultilayerMask': '.mlmask',
                              'Multilayer_Setup': '.mlsetup', 'Multilayer_Mask': '.mlmask',
                              'Multilayer_LayerTemplate': '.mltemplate',
                              'MultilayerLayerTemplate': '.mltemplate', 'entEntityTemplate': '.ent',
                              'appearanceAppearanceResource': '.app'}
                named = {a.fnv(path): path for doc in documents.values() for path in a.depot_paths(doc)}
                mapping = {}
                for key, doc in documents.items():
                    extension = Path(named[key].replace('\\', '/')).suffix if key in named else extensions.get(doc['Data']['RootChunk']['$type'])
                    a.require(extension and len(extension) <= 24 and extension[1:].isalnum(), 'Unsupported clothing resource type: ' + doc['Data']['RootChunk']['$type'])
                    mapping[key] = namespace + f'{key:016x}' + extension
                mapping[a.fnv(template['appPath'])] = namespace + 'item.app'
                mapping[a.fnv(template['entityPath'])] = namespace + 'item.ent'
                for path in parts: mapping[a.fnv(path)] = namespace + f'{a.fnv(path):016x}.ent'
                # Embedded material names must also be private to each colour.
                for doc in documents.values():
                    for embedded in doc['Data'].get('EmbeddedFiles', []):
                        path = embedded.get('FileName', {}).get('$value')
                        if isinstance(path, str): mapping[a.fnv(path)] = namespace + f'{a.fnv(path):016x}' + Path(path.replace('\\', '/')).suffix
                chosen_materials = {}
                for path in paths:
                    mesh = documents[a.fnv(path)]['Data']['RootChunk']
                    a.require(mesh['$type'] == 'CMesh', 'The clothing resource is not a mesh')
                    choices = material_names(mesh)
                    a.require(choices, 'The clothing mesh has no material appearance')
                    old = {x.get('meshAppearance', {}).get('$value') for x in nodes(app)
                           if x.get('mesh', {}).get('DepotPath', {}).get('$value') == path}
                    chosen = next(iter(old)) if len(old) == 1 and next(iter(old)) in choices else 'default' if 'default' in choices else next(iter(choices)) if len(choices) == 1 else None
                    a.require(chosen, 'This garment needs an explicit material variant choice')
                    chosen_materials[path] = chosen
                    select_mesh_appearance(app, path, chosen)
                a.isolate_appearance_names(entity, app, template['prefix'], entity_name + '_')
                for path in parts:
                    part = copy.deepcopy(documents[a.fnv(path)]) if a.fnv(path) in documents else read_json(part_json / (extracted_parts[path].name + '.json'))
                    for mesh_path in paths:
                        if any(x.get('mesh', {}).get('DepotPath', {}).get('$value') == mesh_path for x in nodes(part)):
                            select_mesh_appearance(part, mesh_path, chosen_materials[mesh_path])
                    namespace_paths(part, mapping)
                    edit(mapping[a.fnv(path)], part)
                namespace_paths(entity, mapping)
                namespace_paths(app, mapping)
                edit(namespace + 'item.ent', entity)
                edit(namespace + 'item.app', app)
                for key, doc in documents.items():
                    originals.add(key)
                    if key in {a.fnv(template['entityPath']), a.fnv(template['appPath'])} or key in {a.fnv(p) for p in parts}: continue
                    namespace_paths(doc, mapping)
                    edit(mapping[key], doc)
                for field in ['data', 'compiledData']:
                    rows = factory['Data']['RootChunk'][field]
                    a.require(not any(row[0] == entity_name for row in rows), 'This garment is already in the clothing factory')
                    rows.append([entity_name, namespace + 'item.ent', 'true'])
        edit(a.FACTORY, factory)
        self.convert('deserialize', edits, rebuilt)
        self.convert('serialize', rebuilt, checked)
        for filename, (path, expected) in generated.items():
            actual = read_json(checked / filename)
            a.require(conversion_graph(actual['Data']) == conversion_graph(expected['Data']), 'Clothing graph changed during conversion: ' + path)
            data = (rebuilt / filename.removesuffix('.json')).read_bytes()
            if path == a.FACTORY:
                data = a.mac_factory(data)
                (rebuilt / filename.removesuffix('.json')).write_bytes(data)
            resources[a.fnv(path)] = a.resource_record(path, data)
        self.convert('serialize', rebuilt, checked)
        factory_name = f'{a.fnv(a.FACTORY):016x}.csv.json'
        actual_factory = read_json(checked / factory_name)['Data']['RootChunk']
        for field in ['data', 'compiledData']:
            a.require(actual_factory[field] == factory['Data']['RootChunk'][field], 'The Mac factory changed during relocation')
        a.require(originals.isdisjoint(resources), 'Original clothing assets would be overwritten')
        archive = work / 'clothing-additions.archive'
        a.write_archive(archive, resources)
        result = dict(version=VERSION, archive=str(archive), archiveSHA256=a.sha(archive),
            resources=[f'0x{k:016x}' for k in sorted(resources)], originalResourceHashes=[f'0x{k:016x}' for k in sorted(originals)],
            items=[{key: x[key] for key in ['record', 'name', 'source', 'slot', 'archivePath', 'sourceSHA256', 'entityName']} for x in items])
        atomic_json(self.output / 'assets.json', result)
        # Keep the small archive and receipts, not raw meshes or material buffers.
        for folder in work.iterdir():
            if folder.is_dir(): shutil.rmtree(folder)
        for path in (self.output / 'archives').glob('*.archive'): path.unlink()
        return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--request', type=Path, required=True)
    args = parser.parse_args()
    try: os.nice(10)
    except OSError: pass
    request = json.loads(args.request.read_text())
    converter = Converter(request)
    if request.get('action') == 'build': converter.build()
    else: converter.inspect()


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, OSError, subprocess.TimeoutExpired, zipfile.BadZipFile) as error:
        print('Could not prepare this clothing: ' + str(error), file=sys.stderr)
        sys.exit(1)
